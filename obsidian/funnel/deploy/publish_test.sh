set -eu
vault=$3
if [ "$SCENARIO" = noop ]; then exit 0; fi
if [ "$SCENARIO" = cancel ]; then exec sleep 30; fi
mkdir -p "$vault/Autogenerated"
cp "$FIXTURE" "$vault/Autogenerated/2024-W01 Funnel.md"
case "$SCENARIO" in
 unrelated) printf 'changed' > "$vault/personal.md" ;;
 invalid) printf 'personal' > "$vault/Autogenerated/2024-W01 Funnel.md" ;;
 fatal) exit 1 ;;
 unsafe) printf '../personal.md\n'; exit 0 ;;
esac
printf 'Autogenerated/2024-W01 Funnel.md\n'
if [ "$SCENARIO" = degraded ]; then exit 2; fi
SH
chmod 700 "$root/stub"
export FUNNEL_BIN="$root/stub" FUNNEL_GIT_BRANCH=main
export FUNNEL_GIT_AUTHOR_NAME='Synthetic Automation' FUNNEL_GIT_AUTHOR_EMAIL='automation@example.invalid'
mkdir "$root/temp"
export TMPDIR="$root/temp"
for SCENARIO in fresh degraded noop fatal unrelated invalid unsafe; do
 export SCENARIO
 remote="$root/$SCENARIO.git";seed="$root/$SCENARIO-seed"
 git init --bare -q "$remote"
 git init -q -b main "$seed"
 printf 'personal preserved\n' > "$seed/personal.md"
 git -C "$seed" add personal.md
 git -C "$seed" commit -qm 'Synthetic baseline'
 git -C "$seed" push -q "$remote" HEAD:main
 before=$(git --git-dir="$remote" rev-parse main)
 export FUNNEL_GIT_REMOTE="$remote"
 set +e
 sh "$project/deploy/publish.sh" >"$root/out" 2>"$root/log"
 code=$?
 set -e
 expected=1
 case "$SCENARIO" in fresh|noop) expected=0;; degraded) expected=2;; esac
 if [ "$code" != "$expected" ]; then printf 'FAIL %s: exit %s expected %s\n' "$SCENARIO" "$code" "$expected"; grep '^funnel publisher:' "$root/log" || :; exit 1; fi
 after=$(git --git-dir="$remote" rev-parse main)
 case "$SCENARIO" in
  fresh|degraded) [ "$before" != "$after" ]; git --git-dir="$remote" diff --name-only "$before" "$after" >"$root/actual"; printf 'Autogenerated/2024-W01 Funnel.md\n' >"$root/wanted";cmp "$root/actual" "$root/wanted";;
  *) [ "$before" = "$after" ];;
 esac
 [ "$(git --git-dir="$remote" show main:personal.md)" = 'personal preserved' ]
 [ -z "$(ls -A "$TMPDIR")" ]
 if grep -q 'synthetic-token\|Synthetic outing\|personal preserved' "$root/out" "$root/log"; then exit 1; fi
 printf 'PASS publisher %s\n' "$SCENARIO"
