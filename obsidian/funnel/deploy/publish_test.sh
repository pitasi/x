# Offline: synthetic Markdown and disposable local repositories only.
set -eu
umask 077
root=$(mktemp -d "${TMPDIR:-/tmp}/funnel-publisher-test.XXXXXX")
trap 'rm -rf "$root"' 0
trap 'exit 1' HUP INT TERM
project=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null GIT_TERMINAL_PROMPT=0
export GIT_AUTHOR_NAME='Synthetic Test' GIT_AUTHOR_EMAIL='test@example.invalid'
export GIT_COMMITTER_NAME="$GIT_AUTHOR_NAME" GIT_COMMITTER_EMAIL="$GIT_AUTHOR_EMAIL"
if [ -n "${FUNNEL_TEST_BIN:-}" ]; then
 cp "$FUNNEL_TEST_BIN" "$root/funnel"
else
 GOWORK=off GOTOOLCHAIN=local go build -o "$root/funnel" "$project/cmd/funnel"
fi
mkdir "$root/fixture"
set +e
DAWARICH_URL=http://127.0.0.1:1 DAWARICH_TOKEN=synthetic-token \
PLEX_URL=http://127.0.0.1:1 PLEX_TOKEN=synthetic-token PLEX_USER_ID=7 \
