code=$?
set -e
[ "$code" = 2 ] || { printf 'FAIL synthetic fixture exit %s\n' "$code"; grep '^funnel:' "$root/fixture-log" || :;exit 1; }
export FIXTURE="$root/fixture/Autogenerated/2024-W01 Funnel.md"
cat >"$root/stub" <<'SH'
