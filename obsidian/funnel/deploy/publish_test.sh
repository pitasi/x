set -eu
verb=
for arg do
 case "$arg" in clone|push|fetch) verb=$arg;break;; esac
done
if [ "$SCENARIO" = auth ] && [ "$verb" = clone ]; then exit 1; fi
if [ "$SCENARIO" = unknown ] && [ "$verb" = fetch ]; then exit 1; fi
rival() {
 "$REAL_GIT" clone -q --branch main "$FUNNEL_GIT_REMOTE" "$RIVAL" > /dev/null 2>&1
 printf 'competing personal update\n' > "$RIVAL/personal.md"
 "$REAL_GIT" -C "$RIVAL" add personal.md
 "$REAL_GIT" -C "$RIVAL" commit -qm 'Synthetic competing writer'
 "$REAL_GIT" -C "$RIVAL" push -q origin main
}
if [ "$verb" = push ]; then
 case "$SCENARIO" in
  reject) rival; exec "$REAL_GIT" "$@";;
  lost|unknown) "$REAL_GIT" "$@";exit 1;;
  advanced) "$REAL_GIT" "$@";rival;exit 1;;
 esac
fi
exec "$REAL_GIT" "$@"
SH
chmod 700 "$root/shim/git"
export PATH="$root/shim:$PATH"
for SCENARIO in reject lost advanced unknown auth cancel; do
 export SCENARIO
 remote="$root/$SCENARIO.git";seed="$root/$SCENARIO-seed"
 "$REAL_GIT" init --bare -q "$remote"
 "$REAL_GIT" init -q -b main "$seed"
 printf 'personal preserved\n' > "$seed/personal.md"
 "$REAL_GIT" -C "$seed" add personal.md
 "$REAL_GIT" -C "$seed" commit -qm 'Synthetic baseline'
 "$REAL_GIT" -C "$seed" push -q "$remote" HEAD:main
 export FUNNEL_GIT_REMOTE="$remote" RIVAL="$root/$SCENARIO-rival"
 before=$("$REAL_GIT" --git-dir="$remote" rev-parse main)
 set +e
 if [ "$SCENARIO" = cancel ]; then
  sh "$project/deploy/publish.sh" >"$root/out" 2>"$root/log" & pid=$!
  sleep 1;kill -TERM "$pid";wait "$pid";code=$?
 else
  sh "$project/deploy/publish.sh" >"$root/out" 2>"$root/log";code=$?
 fi
 set -e
 expected=1;case "$SCENARIO" in lost|advanced) expected=0;;esac
 [ "$code" = "$expected" ] || { printf 'FAIL failure scenario %s\n' "$SCENARIO";exit 1; }
 [ -z "$(ls -A "$TMPDIR")" ]
 case "$SCENARIO" in
  unknown) grep -q 'outcome unknown' "$root/log";[ "$("$REAL_GIT" --git-dir="$remote" rev-parse main)" != "$before" ];;
  reject)
   [ "$("$REAL_GIT" --git-dir="$remote" show main:personal.md)" = 'competing personal update' ]
   SCENARIO=retry;export SCENARIO
   sh "$project/deploy/publish.sh" >"$root/out" 2>"$root/log"
   [ "$("$REAL_GIT" --git-dir="$remote" show main:personal.md)" = 'competing personal update' ];;
  lost|advanced) grep -q 'publication confirmed' "$root/log";;
  auth|cancel) [ "$("$REAL_GIT" --git-dir="$remote" rev-parse main)" = "$before" ];;
 esac
 printf 'PASS publisher failure %s\n' "$SCENARIO"
done
